def translate(jp):
    if jp in T:
        return T[jp]
    for subs, en, maxlen in P:
        if maxlen and len(jp) > maxlen:
            continue
        if all(sub in jp for sub in subs):
            return en
    return None

def process_batch(inpath, outpath):
    data = load(inpath)
    result = []
    translated = 0
    for e in data:
        en = translate(e['japanese'])
        if en is None:
            en = ""
        else:
            translated += 1
        result.append({
            "resource": e["resource"],
            "msg_index": e["msg_index"],
            "japanese": e["japanese"],
            "english": en
        })
    save(result, outpath)
    pct = 100*translated//len(result) if result else 0
    print(f"  Translated: {translated}/{len(result)} ({pct}%)")
    missing = [r for r in result if not r['english']]
    if missing:
        print(f"  Missing: {len(missing)}")

