import struct
ee=open("C:/programmieren/wizardrytranslation/build/harvest/_requestperfect/eeMemory.bin","rb").read()
# Body text uses BE-u16 glyph cells, glyph=char-0x20 => cell = (char-0x20)<<8.
# "Duhan" = D,u,h,a,n => chars 0x44,0x75,0x68,0x61,0x6e => cells 0x2400,0x5500,0x4800,0x4100,0x4E00
# search for that BE sequence
import re
needle = bytes([0x24,0x00,0x55,0x00,0x48,0x00,0x41,0x00,0x4E,0x00])  # "Duhan" cells BE
i=ee.find(needle)
print("Duhan-cells (Client value) at", hex(i) if i>=0 else "NOT FOUND")
# "bring" b,r,i,n,g => 0x42,0x72,0x69,0x6e,0x67 => cells 0x2200,0x5200,0x4900,0x4E00,0x4700
needle2=bytes([0x22,0x00,0x52,0x00,0x49,0x00,0x4E,0x00,0x47,0x00])
j=ee.find(needle2)
print("'bring'-cells (body line) at", hex(j) if j>=0 else "NOT FOUND")
# "REQUEST" R,E,Q,U,E,S,T uppercase
needle3=bytes([0x32,0x00,0x25,0x00,0x31,0x00,0x35,0x00,0x25,0x00,0x33,0x00,0x34,0x00])
k=ee.find(needle3)
print("'REQUEST'-cells (header) at", hex(k) if k>=0 else "NOT FOUND")
