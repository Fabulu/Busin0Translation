"""
inject_r39_quest.py - Inject English quest text into R39 (type-15).

This script handles the quest data block in R39 starting at byte 14504:
  G346  (14504): Offset table for quest descriptions -> points into G347-G380 (73 slots)
  G347  (14652): [separator]
  G348-G380:     Quest description bodies
  G381  (19842): Offset table for client names -> points into G382-G410 (66 slots)
  G382  (19976): [separator]
  G383-G410:     Client names / quest event messages
  G411  (20420): Offset table for quest UI labels -> points into G412-G441 (67 slots)
  G412  (20556): [separator]
  G413-G441:     Quest UI labels (Accept/Abandon/Yes/No/Client/Reward etc.)
  G442  (21052): Offset table for quest titles -> points into G443-G476+ (71 slots)
  G443  (21196): [separator]
  G444-G476:     Individual quest titles

All four tables (G346/G381/G411/G442) are offset tables with (value, 0) pairs where
`value` is a uint16 byte offset from the byte immediately after the respective
table's FFFF terminator.

Strategy:
1. Keep all four offset tables SAME SIZE (slot counts unchanged).
2. Rebuild G348-G380 (descriptions) and G383-G410 (client names) with English text
   from data/r39_quest_text_aligned.json (aligned by Japanese-text matching).
3. Rebuild G412-G441 (UI labels) and G443-G476 (quest titles) with English text
   from data/type2_translated/batch_r39_equip_b.json (msg_index == raw group index).
4. Rebuild every offset table's non-zero values to preserve the original
   (target group, glyph ordinal) semantics; table bases shift as earlier groups grow.
5. Groups after G476 keep their content, just shift position.

Output: build/packdata_resources/0039_type15.raw (same format, potentially different size)
The file may grow past the original 13 sectors (26624 bytes); up to 16 sectors is
acceptable (rebuild_packdata.py recomputes the TOC).
"""

import struct, json, os, sys, math

BASE = 'C:/Programmieren/wizardrytranslation'
os.chdir(BASE)
sys.stdout = open(sys.stdout.fileno(), mode='w', encoding='utf-8', buffering=1)

SECTOR = 2048

# ---------------------------------------------------------------------------
# 1. Load the already-patched R39 from the previous build step
#    (inject_r39_v2.py must have run first to produce this file)
# ---------------------------------------------------------------------------
patched_path = 'build/packdata_resources/0039_type15.raw'
orig_path = 'extracted/packdata_raw/0039_type15.raw'

if os.path.exists(patched_path):
    raw = bytearray(open(patched_path, 'rb').read())
    # Trim to original size if it was padded by inject_r39_v2.py
    # inject_r39_v2.py produces exactly 26624 bytes (same as original)
    if len(raw) > 26624:
        raw = raw[:26624]
    print(f"R39 from previous step: {len(raw)} bytes (from {patched_path})")
else:
    raw = bytearray(open(orig_path, 'rb').read())
    print(f"R39 from original: {len(raw)} bytes (inject_r39_v2.py not yet run)")

assert len(raw) == 26624, f"Unexpected R39 size: {len(raw)}"

# ---------------------------------------------------------------------------
# 2. Load translations
# ---------------------------------------------------------------------------
trans_b = json.load(open('data/type2_translated/batch_r39_equip_b.json', encoding='utf-8'))
trans_dict = {e['msg_index']: e for e in trans_b if e.get('english', '').strip()}
print(f"Loaded {len(trans_dict)} translations from batch_r39_equip_b.json")

# Quest descriptions (G348-G380) + client names (G383-G410), keyed by RAW group index.
# Generated by build/recon_v85/quest-r39/align_quest_text.py from batch_r39_equip_a.json.
aligned = json.load(open('data/r39_quest_text_aligned.json', encoding='utf-8'))
aligned_dict = {int(k): v for k, v in aligned.items() if v.get('english', '').strip()}
print(f"Loaded {len(aligned_dict)} aligned quest description/client translations")

# ---------------------------------------------------------------------------
# 3. Load glyph table
# ---------------------------------------------------------------------------
glyph_table = json.load(open('data/english_glyph_table.json', encoding='utf-8'))

def encode_english(text):
    """Encode English text to glyph list. Newlines and ' / ' become FFFE."""
    text = text.replace(' / ', '\n')
    parts = text.split('\n')
    glyphs = []
    for pi, part in enumerate(parts):
        if pi > 0:
            glyphs.append(0xFFFE)
        for ch in part.strip() if pi > 0 else part:
            g = glyph_table.get(ch)
            if g is not None:
                glyphs.append(int(g))
            elif ch == ' ':
                glyphs.append(0)
            else:
                glyphs.append(31)  # '?' fallback
    return glyphs

# ---------------------------------------------------------------------------
# 4. Scan ALL FFFF groups from byte 632
# ---------------------------------------------------------------------------
pos = 632
groups = []      # groups[i] = list of glyph values (FFFF excluded)
group_starts = []  # byte position where group i's first glyph is (right after prev FFFF)
cur_group = []
cur_start = pos
while pos + 1 < len(raw):
    w = struct.unpack_from('>H', raw, pos)[0]
    if w == 0xFFFF:
        groups.append(list(cur_group))
        group_starts.append(cur_start)
        cur_group = []
        cur_start = pos + 2
    else:
        cur_group.append(w)
    pos += 2

print(f"Total FFFF groups in stream: {len(groups)}")

# Verify key positions
assert group_starts[346] == 14504, f"G346 expected at 14504, got {group_starts[346]}"
assert len(groups[346]) == 73, f"G346 expected 73 glyphs, got {len(groups[346])}"
assert group_starts[381] == 19842, f"G381 expected at 19842, got {group_starts[381]}"
assert len(groups[381]) == 66, f"G381 expected 66 glyphs, got {len(groups[381])}"
assert group_starts[411] == 20420, f"G411 expected at 20420, got {group_starts[411]}"
assert len(groups[411]) == 67, f"G411 expected 67 glyphs, got {len(groups[411])}"
assert group_starts[442] == 21052, f"G442 expected at 21052, got {group_starts[442]}"
assert len(groups[442]) == 71, f"G442 expected 71 glyphs, got {len(groups[442])}"
assert group_starts[347] == 14652, f"G347 expected at 14652, got {group_starts[347]}"
assert group_starts[382] == 19976, f"G382 expected at 19976, got {group_starts[382]}"
assert group_starts[412] == 20556, f"G412 expected at 20556, got {group_starts[412]}"
assert group_starts[443] == 21196, f"G443 expected at 21196, got {group_starts[443]}"

# Offset tables: group index -> base (byte immediately after the table's FFFF)
TABLE_GROUPS = [346, 381, 411, 442]
table_bases = {t: group_starts[t] + len(groups[t]) * 2 + 2 for t in TABLE_GROUPS}
assert table_bases[346] == 14652 and table_bases[381] == 19976
assert table_bases[411] == 20556 and table_bases[442] == 21196

print("Structure assertions passed.")

# ---------------------------------------------------------------------------
# 5. Build semantic maps for the four offset tables (G346/G381/G411/G442)
# ---------------------------------------------------------------------------

def build_offset_semantics(table_raw_values, base, groups, group_starts):
    """
    For each non-zero value in table_raw_values, find which group+glyph_idx it points to.
    Returns list of (slot_index, orig_offset, group_idx, glyph_idx).
    """
    semantics = []
    for slot_i, v in enumerate(table_raw_values):
        if v != 0 and v != 0xFFFF and v != 0xFFFE:
            target = base + v
            found = False
            for gi, gs in enumerate(group_starts):
                ge = gs + len(groups[gi]) * 2 + 2
                if gs <= target < ge:
                    glyph_idx = (target - gs) // 2
                    semantics.append((slot_i, v, gi, glyph_idx))
                    found = True
                    break
            if not found:
                print(f"  WARNING: offset {v} -> target {target} not found in any group")
                semantics.append((slot_i, v, -1, 0))
    return semantics

table_raw = {}        # table group -> list of original uint16 slot values
table_semantics = {}  # table group -> [(slot_i, orig_v, group_idx, glyph_idx), ...]
for t in TABLE_GROUPS:
    table_raw[t] = list(groups[t])
    table_semantics[t] = build_offset_semantics(table_raw[t], table_bases[t], groups, group_starts)
    print(f"G{t}: {len(table_semantics[t])} non-zero offset entries")

# ---------------------------------------------------------------------------
# 6. Build new group content for G348-G410 (descriptions/clients) and G412-G476
# ---------------------------------------------------------------------------

# Groups to translate (replace Japanese with English):
# G348-G380: quest descriptions (aligned_dict, keyed by raw group index)
# G383-G410: client names / event messages (aligned_dict)
# G412-G441: quest UI labels (trans_dict, msg_index = group_idx)
# G443-G476: quest titles (trans_dict)
# G346/G381/G411/G442: offset tables, handled separately. G347/G382/G412/G443: separators.

TRANSLATE_GROUPS = set(range(412, 477))  # G412-G476 inclusive
TRANSLATE_GROUPS.discard(442)  # G442 is an offset table, not plain text
ALIGNED_GROUPS = set(range(348, 381)) | set(range(383, 411))

new_groups = {i: list(groups[i]) for i in range(len(groups))}  # copy all

translated = 0
kept_original = 0

for gi in sorted(TRANSLATE_GROUPS | ALIGNED_GROUPS):
    entry = aligned_dict.get(gi) if gi in ALIGNED_GROUPS else trans_dict.get(gi)
    if entry and entry.get('english', '').strip():
        en = entry['english'].strip()
        en_glyphs = encode_english(en)
        # Add FFFE at end to match Japanese pattern (groups end with FFFE before FFFF)
        if en_glyphs and en_glyphs[-1] != 0xFFFE:
            en_glyphs.append(0xFFFE)
        new_groups[gi] = en_glyphs
        translated += 1
    else:
        kept_original += 1

print(f"Translated: {translated} groups, kept original: {kept_original} groups")

# ---------------------------------------------------------------------------
# 7. Compute new byte positions for all groups from G346 onwards
# ---------------------------------------------------------------------------

def group_byte_size(gi):
    """Total bytes for group gi including FFFF: len(glyphs)*2 + 2."""
    return len(new_groups[gi]) * 2 + 2

REBUILD_FIRST_GROUP = 346
# G346 starts at 14504 (unchanged; everything before it is untouched)
original_prefix_end = group_starts[REBUILD_FIRST_GROUP]
assert original_prefix_end == 14504, f"Prefix end expected 14504, got {original_prefix_end}"
new_group_starts = {i: group_starts[i] for i in range(REBUILD_FIRST_GROUP)}  # unchanged groups

current_pos = original_prefix_end
for gi in range(REBUILD_FIRST_GROUP, len(groups)):
    new_group_starts[gi] = current_pos
    current_pos += group_byte_size(gi)

new_file_len = current_pos

old_total = len(raw)
print(f"Old end: {old_total} bytes, New end: {new_file_len} bytes (delta: {new_file_len - old_total:+d})")

# ---------------------------------------------------------------------------
# 8. Compute new offset values for all four tables (G346/G381/G411/G442)
#    Each non-zero slot must keep pointing at the same (group, glyph ordinal).
#    Table bases shift because groups before them grow.
# ---------------------------------------------------------------------------

for t in TABLE_GROUPS:
    new_base = new_group_starts[t] + group_byte_size(t)
    print(f"G{t} base: old={table_bases[t]}, new={new_base} (delta={new_base - table_bases[t]:+d})")

    new_vals = list(table_raw[t])  # copy (slot count unchanged)
    changes = 0
    for slot_i, orig_v, gi, glyph_idx in table_semantics[t]:
        if gi < 0:
            continue
        new_gs = new_group_starts[gi]
        new_target = new_gs + glyph_idx * 2
        new_offset = new_target - new_base
        if new_offset < 0:
            print(f"  WARNING: G{t} slot[{slot_i}]: negative offset {new_offset}")
            new_offset = 0
        elif new_offset > 65534:
            print(f"  WARNING: G{t} slot[{slot_i}]: offset overflow {new_offset}")
            new_offset = 65534
        if table_raw[t][slot_i] != new_offset:
            changes += 1
        new_vals[slot_i] = new_offset

    new_groups[t] = new_vals
    print(f"G{t}: {changes} offset values updated")

# ---------------------------------------------------------------------------
# 10. Rebuild the binary
# ---------------------------------------------------------------------------

out = bytearray()

# Prefix: bytes 0 to 14504 (unchanged)
out += raw[:original_prefix_end]

# Groups G346 onwards (rebuilt with new content and/or updated offsets)
for gi in range(REBUILD_FIRST_GROUP, len(groups)):
    glyph_data = new_groups[gi]
    for g in glyph_data:
        out += struct.pack('>H', g)
    out += struct.pack('>H', 0xFFFF)

assert len(out) == new_file_len, f"Size mismatch: {len(out)} vs {new_file_len}"

# Pad to sector boundary
sectors = math.ceil(len(out) / SECTOR)
padded_size = sectors * SECTOR
out += b'\x00' * (padded_size - len(out))

print()
print(f"Output: {len(out)} bytes ({sectors} sectors)")
if sectors > 16:
    print("  ERROR: Exceeds 16-sector limit! Shorten the longest quest descriptions.")
    sys.exit(1)
elif sectors > 13:
    print(f"  NOTE: Grew from 13 to {sectors} sectors -- rebuild_packdata.py recomputes the TOC.")

# Write output
os.makedirs('build/packdata_resources', exist_ok=True)
out_path = 'build/packdata_resources/0039_type15.raw'
with open(out_path, 'wb') as f:
    f.write(out)
print(f"Written to {out_path}")

# ---------------------------------------------------------------------------
# 11. Verification: re-scan and check quest label groups
# ---------------------------------------------------------------------------
print()
print("=== Verification: quest label groups ===")
glyph_map_data = json.load(open('data/glyph_map_partial.json', encoding='utf-8'))

def decode_glyphs(glyphs):
    result = ''
    for g in glyphs:
        if g == 0xFFFE: result += '[LB]'
        elif g == 0xFFFF: result += '[END]'
        elif 0 <= g < 95: result += chr(0x20 + g)
        else: result += glyph_map_data.get(str(g), f'[{g:04X}]')
    return result

# Re-scan the output file
pos2 = 632
new_groups_scan = []
new_starts_scan = []
cur_g2 = []
cur_s2 = pos2
check_data = bytearray(out)
while pos2 + 1 < len(check_data):
    w = struct.unpack_from('>H', check_data, pos2)[0]
    if w == 0xFFFF:
        new_groups_scan.append(list(cur_g2))
        new_starts_scan.append(cur_s2)
        cur_g2 = []
        cur_s2 = pos2 + 2
    else:
        cur_g2.append(w)
    pos2 += 2

print(f"Re-scanned groups: {len(new_groups_scan)}")
print()

# Check key groups
check_indices = [348, 353, 380, 383, 388, 410,
                 413, 414, 415, 416, 417, 418, 419, 420, 421, 422, 424, 425, 426,
                 427, 428, 429, 430, 431, 432, 433, 436, 437, 438, 441,
                 444, 445, 446, 449, 450, 456, 460, 476]
for idx in check_indices:
    if idx < len(new_groups_scan):
        dec = decode_glyphs(new_groups_scan[idx])
        src = aligned_dict if idx in ALIGNED_GROUPS else trans_dict
        exp_en = src.get(idx, {}).get('english', '(no translation)')
        exp_en = exp_en.replace('\n', ' / ')
        print(f"  G{idx}: '{dec}' | expected: '{exp_en}'")

print()
print("Done.")
